//! Build-time faithful lowering of the MySQL grammar's semantic predicates.
//!
//! The generated lexer/parser dispatch semantic predicates by opaque
//! `(rule_index, pred_index)` integers; the predicate *body* text lives only in
//! the `semantics.json` manifests emitted alongside the code. Because the
//! benchmark fixes `serverVersion = 80400` and `sqlMode = "ANSI_QUOTES"`, every
//! `serverVersion <op> N` / `isSqlModeActive(Mode)` predicate collapses to a
//! compile-time constant — identical to what the C++/TS base classes evaluate at
//! runtime, but free.
//!
//! Two lexer predicates are *stateful* (`checkMySQLVersion`, `inVersionComment`)
//! and cannot be precomputed; the build emits their coordinates as constants so
//! the hook can special-case them.
//!
//! Fidelity discipline: any predicate body the parser below does not recognise
//! is a hard build error (never a silent default), matching the runtime's
//! `UnknownSemanticPolicy::Error`.

use std::env;
use std::fs;
use std::path::Path;

/// Benchmark-fixed server version (`typescript-runner.ts`: `tokenize(stmt, 80400, ...)`).
const SERVER_VERSION: u32 = 80_400;

/// Benchmark-fixed SQL mode bitmask. `"ANSI_QUOTES"` activates only `AnsiQuotes`
/// (`MySQLRecognizerCommon::sqlModeFromString`), leaving IgnoreSpace /
/// PipesAsConcat / HighNotPrecedence / NoBackslashEscapes inactive.
const SQL_MODE: u32 = SQL_MODE_ANSI_QUOTES;
const SQL_MODE_ANSI_QUOTES: u32 = 1 << 0;
const SQL_MODE_HIGH_NOT_PRECEDENCE: u32 = 1 << 1;
const SQL_MODE_PIPES_AS_CONCAT: u32 = 1 << 2;
const SQL_MODE_IGNORE_SPACE: u32 = 1 << 3;
const SQL_MODE_NO_BACKSLASH_ESCAPES: u32 = 1 << 4;

fn main() {
    let out_dir = env::var("OUT_DIR").expect("OUT_DIR set by cargo");
    let gen = Path::new("src/generated");

    let lexer = parse_manifest(&gen.join("lexer_semantics.json"), "lexer");
    let parser = parse_manifest(&gen.join("parser_semantics.json"), "parser");

    let mut out = String::new();
    out.push_str("// @generated by build.rs from semantics.json — do not edit.\n\n");

    emit_pred_table(&mut out, "PARSER_PRED", &parser.predicates);
    emit_pred_table(&mut out, "LEXER_PRED", &lexer.predicates);
    emit_action_table(&mut out, &lexer.actions);

    fs::write(Path::new(&out_dir).join("semantics_tables.rs"), out)
        .expect("write semantics_tables.rs");

    println!("cargo:rerun-if-changed=src/generated/lexer_semantics.json");
    println!("cargo:rerun-if-changed=src/generated/parser_semantics.json");
    println!("cargo:rerun-if-changed=build.rs");
}

/// A precomputed predicate: either a constant boolean, or a runtime-evaluated
/// stateful predicate (identified by its C++ base-class method name).
enum Pred {
    Const(bool),
    Stateful(&'static str),
    /// A `pred_index` present in the ATN numbering space but with no transition
    /// in this grammar's serialized ATN (gap). Never dispatched; panics if hit.
    Unreachable,
}

/// A lexer custom action lowered to a dispatch tag the hook understands.
struct ActionEntry {
    index: usize,
    tag: String,
}

struct Manifest {
    /// Predicates indexed by dense `pred_index`.
    predicates: Vec<Pred>,
    /// Actions (lexer only), sorted by `action_index`.
    actions: Vec<ActionEntry>,
}

fn parse_manifest(path: &Path, kind: &str) -> Manifest {
    let text = fs::read_to_string(path)
        .unwrap_or_else(|e| panic!("read {}: {e}", path.display()));
    let json: serde_json::Value =
        serde_json::from_str(&text).unwrap_or_else(|e| panic!("parse {}: {e}", path.display()));

    let grammar = json["grammars"]
        .as_array()
        .expect("grammars array")
        .iter()
        .find(|g| g["kind"] == kind)
        .unwrap_or_else(|| panic!("no {kind} grammar in {}", path.display()));

    let coords = grammar["coordinates"].as_array().expect("coordinates array");

    // Predicates: collect (index, body), then place into a dense vec by index.
    let mut preds: Vec<(usize, String)> = Vec::new();
    let mut actions: Vec<ActionEntry> = Vec::new();
    for c in coords {
        let ckind = c["kind"].as_str().unwrap_or("");
        let body = c["body"].as_str().unwrap_or("").trim().to_string();
        match ckind {
            "parser-predicate" | "lexer-predicate" => {
                let index = c["index"].as_u64().expect("predicate index") as usize;
                preds.push((index, body));
            }
            "lexer-action" => {
                let index = c["index"].as_u64().expect("action index") as usize;
                actions.push(ActionEntry { index, tag: lower_action(&body) });
            }
            // Synthetic parser actions carry a null index and no body; the
            // parser recognizer handles them internally (not via the hook).
            "parser-action" => {}
            other => panic!("unexpected coordinate kind {other:?} in {}", path.display()),
        }
    }

    let max = preds.iter().map(|(i, _)| *i).max().map_or(0, |m| m + 1);
    let mut predicates: Vec<Option<Pred>> = (0..max).map(|_| None).collect();
    for (index, body) in preds {
        let pred = lower_predicate(&body);
        assert!(
            predicates[index].is_none(),
            "duplicate {kind} pred_index {index}"
        );
        predicates[index] = Some(pred);
    }
    // Gaps in the index space (predicate slots with no ATN transition) are
    // filled with `Unreachable` — they can never be dispatched.
    let predicates = predicates
        .into_iter()
        .map(|p| p.unwrap_or(Pred::Unreachable))
        .collect();

    actions.sort_by_key(|a| a.index);
    Manifest { predicates, actions }
}

/// Evaluate a `serverVersion`/`sqlMode` predicate body to a compile-time boolean,
/// or mark it stateful. Panics on any unrecognised shape (fail-loud fidelity).
fn lower_predicate(body: &str) -> Pred {
    // Stateful lexer predicates — evaluated at runtime by the hook.
    if body == "inVersionComment" {
        return Pred::Stateful("in_version_comment");
    }
    if body.starts_with("checkMySQLVersion") {
        return Pred::Stateful("check_mysql_version");
    }
    Pred::Const(eval_bool(body))
}

/// Evaluate a boolean predicate expression over `&&` of atoms.
fn eval_bool(body: &str) -> bool {
    body.split("&&").map(str::trim).map(eval_atom).all(|b| b)
}

/// Evaluate one atom: `serverVersion <op> N`, `isSqlModeActive(Mode)`, optionally `!`-negated.
fn eval_atom(atom: &str) -> bool {
    let (negated, atom) = atom
        .strip_prefix('!')
        .map_or((false, atom), |rest| (true, rest.trim()));

    let value = if let Some(rest) = atom.strip_prefix("isSqlModeActive(") {
        let mode = rest.trim_end_matches(')').trim();
        (SQL_MODE & sql_mode_flag(mode)) != 0
    } else if let Some(rest) = atom.strip_prefix("serverVersion") {
        let rest = rest.trim();
        let (op, num) = split_op(rest);
        let n: u32 = num.trim().parse().unwrap_or_else(|_| panic!("bad version int in {atom:?}"));
        match op {
            ">=" => SERVER_VERSION >= n,
            "<=" => SERVER_VERSION <= n,
            ">" => SERVER_VERSION > n,
            "<" => SERVER_VERSION < n,
            "==" => SERVER_VERSION == n,
            "!=" => SERVER_VERSION != n,
            _ => panic!("unknown op {op:?} in {atom:?}"),
        }
    } else {
        panic!("unrecognised predicate atom: {atom:?}");
    };

    value ^ negated
}

fn split_op(rest: &str) -> (&str, &str) {
    for op in [">=", "<=", "==", "!=", ">", "<"] {
        if let Some(num) = rest.strip_prefix(op) {
            return (op, num);
        }
    }
    panic!("no comparison operator in {rest:?}");
}

fn sql_mode_flag(mode: &str) -> u32 {
    match mode {
        "AnsiQuotes" => SQL_MODE_ANSI_QUOTES,
        "HighNotPrecedence" => SQL_MODE_HIGH_NOT_PRECEDENCE,
        "PipesAsConcat" => SQL_MODE_PIPES_AS_CONCAT,
        "IgnoreSpace" => SQL_MODE_IGNORE_SPACE,
        "NoBackslashEscapes" => SQL_MODE_NO_BACKSLASH_ESCAPES,
        other => panic!("unknown SqlMode {other:?}"),
    }
}

/// Lower a lexer action body to a dispatch tag string the hook matches on.
/// Panics on any unrecognised action (fail-loud fidelity).
fn lower_action(body: &str) -> String {
    let b = body.trim().trim_end_matches(';').trim();
    if let Some(rest) = b.strip_prefix("setType(determineFunction(") {
        let proposed = rest.trim_end_matches(')').trim();
        // Qualify the proposed token constant so it resolves in the hook module.
        return format!("DetermineFunction(crate::generated::my_sql_lexer::{proposed})");
    }
    match b {
        "setType(determineNumericType(getText()))" => "DetermineNumericType".into(),
        "emitDot()" => "EmitDot".into(),
        "setType(checkCharset(getText()))" => "CheckCharset".into(),
        "inVersionComment = true" => "EnterVersionComment".into(),
        "inVersionComment = false" => "ExitVersionComment".into(),
        s if s.contains("PipesAsConcat") && s.contains("CONCAT_PIPES_SYMBOL") => "PipesOr".into(),
        s if s.contains("HighNotPrecedence") && s.contains("NOT2_SYMBOL") => "HighNotPrec".into(),
        other => panic!("unrecognised lexer action: {other:?}"),
    }
}

fn emit_pred_table(out: &mut String, name: &str, preds: &[Pred]) {
    // Constant table: precomputed boolean per pred_index (stateful → false placeholder,
    // never read; the hook dispatches stateful indices before consulting the table).
    out.push_str(&format!(
        "pub static {name}: [PredKind; {}] = [\n",
        preds.len()
    ));
    for p in preds {
        match p {
            Pred::Const(b) => out.push_str(&format!("    PredKind::Const({b}),\n")),
            Pred::Stateful(tag) => {
                out.push_str(&format!("    PredKind::Stateful(Stateful::{}),\n", cap(tag)));
            }
            Pred::Unreachable => out.push_str("    PredKind::Unreachable,\n"),
        }
    }
    out.push_str("];\n\n");
}

fn emit_action_table(out: &mut String, actions: &[ActionEntry]) {
    out.push_str(&format!(
        "pub static LEXER_ACTION: [ActionKind; {}] = [\n",
        actions.len()
    ));
    for a in actions {
        out.push_str(&format!("    ActionKind::{}, // action_index {}\n", a.tag, a.index));
    }
    out.push_str("];\n");
}

/// `in_version_comment` → `InVersionComment`
fn cap(snake: &str) -> String {
    snake
        .split('_')
        .map(|w| {
            let mut c = w.chars();
            c.next()
                .map(|f| f.to_uppercase().collect::<String>() + c.as_str())
                .unwrap_or_default()
        })
        .collect()
}
